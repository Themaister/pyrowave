function rate = rates(W, H, fps, chroma444, hdr10)
	rate = 125 * ((W * H) / (1280 * 720)) ^ 0.4;
	rate *= 1.0 + 0.15 * chroma444;
	rate *= 1.0 + 0.25 * hdr10;
	rate = rate * fps / 60;
endfunction

